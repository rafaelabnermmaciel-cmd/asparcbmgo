-- ============================================================================
-- Painel de Captação (CBM-GO) — script de configuração do banco Supabase.
--
-- Como usar: Supabase → seu projeto → menu "SQL Editor" → "New query" → cole ESTE ARQUIVO
-- INTEIRO → botão "Run". Pode rodar de novo sem medo (todos os comandos são "se não existir"
-- / "sem duplicar"), então não tem problema clicar duas vezes.
--
-- O que este script cria:
--   1. Tabela "quarteis"       — as unidades (OBMs) do CBMGO (editável no site, aba
--                                 Acesso restrito, ou pelo Table Editor do Supabase)
--   2. Tabela "militares"      — um militar por linha, com posto, RG e nome, disponível pra
--                                 virar "responsável" de uma captação (também editável no
--                                 site, aba Acesso restrito) — nem todo mundo já está
--                                 vinculado a um quartel, isso é feito manualmente ali
--   3. Tabela "stakeholders"   — pessoas que tratam de captação com um ou mais parlamentares
--                                 ao mesmo tempo (cadastrado na aba Cadastrar primeiro contato)
--   4. Tabela "captacoes"      — os cadastros feitos pelo formulário do site (sempre nascem
--                                 como "Primeiro contato")
--   4.1. Tabela "captacao_eventos" — os andamentos (linha do tempo) de cada captação
--   4.2. Tabela "usuarios_aprovados" + gatilho — login e aprovação de acesso (só Acesso restrito)
--   5. Regras de segurança (RLS) de cada tabela
--   6. Um espaço de arquivos ("bucket") chamado "anexos" pras fotos/documentos do cadastro
--   7. Tempo real pra tabela de captações
--   8. As 129 unidades do CBMGO (página oficial de contatos, atualizada 12/08/2026) e os
--      militares dos Almanaques de Oficiais e Praças (10/08/2026)
--   9. Vínculo automático de quem comanda cada unidade (por nome, cruzando com o Almanaque)
-- ============================================================================

-- 1) QUARTÉIS ----------------------------------------------------------------
create table if not exists quarteis (
  id text primary key,           -- código curto, sem espaço/acento (ex: "8-bbm")
  nome text not null,            -- nome que aparece no site (ex: "8º BBM")
  municipio text not null default '',
  tipo text not null default ''  -- livre — "BBM", "CIBM", "CRBM" etc.
);

-- Limpeza: a versão anterior deste script guardava um resumo de responsáveis direto na
-- tabela de quartéis; agora isso vira a tabela "militares" (linha por pessoa, ver abaixo).
alter table quarteis drop column if exists responsavel_padrao;

-- 2) MILITARES ------------------------------------------------------------------
-- Um militar por linha, exatamente como na Convocação nº 106/2026: posto/graduação, RG, o
-- "nome de guerra" (a parte em CAIXA ALTA no documento original) e o quartel (OBM).
create table if not exists militares (
  id bigint generated always as identity primary key,
  posto text not null default '',
  rg text not null default '',
  nome text not null default '',
  quartel_id text references quarteis(id) on delete cascade
);

-- Garante "on delete cascade" mesmo se a tabela já existia de uma execução anterior sem
-- isso — apagar um quartel pela aba Acesso restrito remove junto os militares dele, em vez de
-- travar com erro de referência.
alter table militares drop constraint if exists militares_quartel_id_fkey;
alter table militares add constraint militares_quartel_id_fkey foreign key (quartel_id) references quarteis(id) on delete cascade;

-- Agora que o Almanaque inteiro (Oficiais + Praças) entra como militar disponível pra virar
-- "responsável", nem todo mundo já está vinculado a um quartel — a vinculação de quem falta
-- é feita manualmente depois, pela aba Acesso restrito → Militares. Por isso o quartel deixa
-- de ser obrigatório (útil pra quem já rodou uma versão anterior deste script, que exigia).
alter table militares alter column quartel_id drop not null;

-- Cada militar (RG) só pode aparecer uma vez — permite rodar o "insert" da seção 8 de novo
-- sem apagar a tabela toda (o "on conflict" abaixo atualiza posto/nome mas NUNCA mexe no
-- quartel_id de quem já foi vinculado manualmente, então o vínculo feito por vocês na aba
-- Acesso restrito nunca é perdido rodando este script de novo).
alter table militares drop constraint if exists militares_rg_key;
alter table militares add constraint militares_rg_key unique (rg);

-- 3) STAKEHOLDERS ---------------------------------------------------------------
-- Pessoa (ex: um prefeito, um assessor) que trata de algum projeto/captação junto a um ou
-- MAIS DE UM parlamentar ao mesmo tempo — por isso "parlamentares_keys" é uma lista, não um
-- valor só. Cada item da lista é "camara:<id>" ou "senado:<id>" (o <id> é o número que aparece
-- na URL do perfil daquele parlamentar no site, ex.: .../parlamentares/camara/220565 →
-- "camara:220565"). Cadastrado pela aba "Cadastrar primeiro contato" do site (seção Stakeholders);
-- aparece pra escolher ali mesmo (formulário de captação) e no perfil de cada parlamentar
-- vinculado — totalmente editável no site, não precisa mexer no Supabase.
create table if not exists stakeholders (
  id bigint generated always as identity primary key,
  nome text not null default '',
  cargo text not null default '',
  telefone text not null default '',
  projeto text not null default '',
  observacoes text not null default '',
  parlamentares_keys text[] not null default '{}'
);

-- Migração de versões anteriores deste script ------------------------------------
-- a) versão original: tabela "interlocutores" (1 contato por parlamentar, nunca virou
-- "stakeholders") — só roda se ela ainda existir.
do $$
begin
  if exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'interlocutores') then
    insert into stakeholders (nome, cargo, telefone, observacoes, parlamentares_keys)
    select nome, cargo, telefone, observacoes,
           case when parlamentar_key is not null and parlamentar_key <> '' then array[parlamentar_key] else '{}'::text[] end
    from interlocutores;
    drop table interlocutores;
  end if;
end $$;

-- b) versão intermediária: "stakeholders" já existia, mas com 1 parlamentar só por linha
-- (coluna "parlamentar_key" em vez da lista "parlamentares_keys") — só roda se essa coluna
-- antiga ainda existir.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'stakeholders' and column_name = 'parlamentar_key') then
    alter table stakeholders add column if not exists parlamentares_keys text[] not null default '{}';
    update stakeholders set parlamentares_keys = array[parlamentar_key]
      where parlamentar_key is not null and parlamentar_key <> '' and (parlamentares_keys is null or parlamentares_keys = '{}');
    alter table stakeholders drop column parlamentar_key;
  end if;
end $$;

alter table stakeholders add column if not exists projeto text not null default '';
alter table stakeholders drop column if exists email;

-- 4) CAPTAÇÕES ----------------------------------------------------------------
create table if not exists captacoes (
  id bigint generated always as identity primary key,
  criado_em timestamptz not null default now(),
  quartel_id text not null references quarteis(id),
  quartel_nome text not null default '',
  municipio text not null default '',
  responsavel text not null default '',
  stakeholder text not null default '',
  parlamentar_nome text not null default '',
  objeto text not null default '',
  valor_previsto numeric not null default 0,
  status text not null default 'Primeiro contato',
  observacoes text not null default '',  -- "Descrição" no site (nome da coluna mantido por compatibilidade)
  anexos jsonb not null default '[]'::jsonb  -- [{ nome, tipo, tamanho, url }, ...]
);

-- Toda captação nova é só "Primeiro contato" (sem estágio pra escolher no cadastro) — vira
-- "Em articulação" sozinha assim que o primeiro andamento é lançado, e só sai daí quando o
-- militar marca "Indicado" ou "Arquivado" pela aba de andamentos (ver 4.1). Os antigos estágios
-- intermediários (Agenda marcada/Adiado/Recusado/Destinado) somem — quem já estava
-- num deles vira "Em articulação" pra continuar em aberto, sem perder o histórico de eventos.
update captacoes set status = 'Em articulação'
  where status not in ('Primeiro contato', 'Em articulação', 'Indicado', 'Arquivado');
alter table captacoes drop column if exists valor_confirmado;
alter table captacoes drop column if exists num_reunioes;
alter table captacoes drop column if exists data_agenda;

-- 4.1) ANDAMENTOS (LINHA DO TEMPO) DA CAPTAÇÃO ------------------------------------
-- Cada "andamento" (reunião, visita, atualização) registrado dentro de uma captação — com
-- data, descrição, quem esteve presente e anexos (foto/documento). Lançar um andamento aqui é
-- o que alimenta a linha do tempo e o alerta de "esfriando" (calculado no site a partir da
-- data do andamento mais recente). Enquanto só existem andamentos, a captação fica "Em
-- articulação"; o desfecho final ("Indicado" ou "Arquivado") é escolhido nesta mesma aba e
-- muda o status lá na tabela "captacoes" (não fica guardado aqui).
create table if not exists captacao_eventos (
  id bigint generated always as identity primary key,
  captacao_id bigint not null references captacoes(id) on delete cascade,
  data date not null default current_date,
  descricao text not null default '',
  presentes text not null default '',
  anexos jsonb not null default '[]'::jsonb,  -- [{ nome, tipo, tamanho, url }, ...] (foto/documento)
  criado_em timestamptz not null default now()
);

alter table captacao_eventos add column if not exists presentes text not null default '';
alter table captacao_eventos add column if not exists anexos jsonb not null default '[]'::jsonb;

-- 4.2) LOGIN E APROVAÇÃO DE ACESSO (só pra aba Acesso restrito) -------------------
-- Quartéis/militares são dado sensível de organização interna, então quem edita precisa
-- entrar com login (e-mail/senha) E já ter sido aprovado pelo administrador — o resto do
-- site (Cadastro, Stakeholders, Parlamentares) continua aberto pra quem tiver o link, sem
-- mudança nenhuma.
--
-- O e-mail do administrador (trocar aqui se não for esse) já entra liberado sozinho, sem
-- precisar de nenhum passo manual — é comparado sem diferenciar maiúscula/minúscula.
-- Qualquer outra conta nova (criada ao entrar pela primeira vez) cai "aprovado = false" e
-- fica esperando o administrador liberar pela aba Acesso restrito → Acessos — e o administrador
-- recebe um e-mail avisando (ver EMAILJS_TEMPLATE_ID_ACESSO em src/lib/emailjs-config.js e
-- SETUP.md, seção 7).
create table if not exists usuarios_aprovados (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  aprovado boolean not null default false,
  criado_em timestamptz not null default now()
);

-- Gatilho: toda vez que alguém se cadastra (auth.users), já cria a linha correspondente aqui —
-- "aprovado = true" só se o e-mail for o do administrador, "false" (esperando aprovação) pra
-- qualquer outro.
create or replace function public.lidar_com_novo_usuario()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.usuarios_aprovados (user_id, email, aprovado)
  values (new.id, new.email, lower(new.email) = lower('rafaelabnermmaciel@gmail.com'))
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.lidar_com_novo_usuario();

-- Garante que o administrador está liberado e que ninguém mais ficou liberado por engano
-- (ex: numa execução anterior deste script, quando todo mundo entrava liberado na hora).
update usuarios_aprovados set aprovado = true where lower(email) = lower('rafaelabnermmaciel@gmail.com');
update usuarios_aprovados set aprovado = false where lower(email) <> lower('rafaelabnermmaciel@gmail.com');

-- Função auxiliar (roda com privilégio de dono da tabela, ignorando RLS por dentro) pra
-- checar se quem está logado agora já foi aprovado — evita loop de RLS "checando a própria
-- tabela que tem RLS" e é reaproveitada nas políticas de quarteis/militares logo abaixo.
create or replace function public.esta_aprovado()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select coalesce((select aprovado from usuarios_aprovados where user_id = auth.uid()), false);
$$;

-- 5) REGRAS DE SEGURANÇA (RLS) -------------------------------------------------
-- Com RLS ligado, ninguém consegue ler/escrever nada a menos que exista uma política
-- explícita liberando. Aqui: todo mundo pode LER as 4 tabelas (o site é público), e todas as
-- 4 também aceitam criar/editar/apagar linha vindo do próprio site (aba Acesso restrito pra
-- quartéis/militares, Cadastro/edição inline pra captações, e o perfil do parlamentar pra
-- stakeholders) — nenhuma delas precisa do Table Editor do Supabase pra ser mantida no dia a
-- dia.
--
-- Aviso: como o site não tem login, esse acesso de escrita fica aberto pra qualquer pessoa
-- que tenha o link do site — não só quem administra. Pra um painel interno pequeno isso
-- costuma ser um risco aceitável (é o mesmo modelo do formulário de Cadastro), mas não é o
-- ideal pra um sistema com muita gente de fora tendo acesso.
alter table quarteis enable row level security;
alter table militares enable row level security;
alter table stakeholders enable row level security;
alter table captacoes enable row level security;
alter table captacao_eventos enable row level security;
alter table usuarios_aprovados enable row level security;

-- Leitura de quarteis/militares continua pública (o Cadastro e o Dashboard precisam ler sem
-- login) — só criar/editar/apagar passa a exigir login aprovado, pela aba Acesso restrito.
drop policy if exists "Leitura pública" on quarteis;
create policy "Leitura pública" on quarteis for select using (true);
drop policy if exists "Inserção pública" on quarteis;
drop policy if exists "Inserção autenticada aprovada" on quarteis;
create policy "Inserção autenticada aprovada" on quarteis for insert with check (public.esta_aprovado());
drop policy if exists "Atualização pública" on quarteis;
drop policy if exists "Atualização autenticada aprovada" on quarteis;
create policy "Atualização autenticada aprovada" on quarteis for update using (public.esta_aprovado()) with check (public.esta_aprovado());
drop policy if exists "Remoção pública" on quarteis;
drop policy if exists "Remoção autenticada aprovada" on quarteis;
create policy "Remoção autenticada aprovada" on quarteis for delete using (public.esta_aprovado());

drop policy if exists "Leitura pública" on militares;
create policy "Leitura pública" on militares for select using (true);
drop policy if exists "Inserção pública" on militares;
drop policy if exists "Inserção autenticada aprovada" on militares;
create policy "Inserção autenticada aprovada" on militares for insert with check (public.esta_aprovado());
drop policy if exists "Atualização pública" on militares;
drop policy if exists "Atualização autenticada aprovada" on militares;
create policy "Atualização autenticada aprovada" on militares for update using (public.esta_aprovado()) with check (public.esta_aprovado());
drop policy if exists "Remoção pública" on militares;
drop policy if exists "Remoção autenticada aprovada" on militares;
create policy "Remoção autenticada aprovada" on militares for delete using (public.esta_aprovado());

-- Qualquer pessoa logada vê a lista (nome/e-mail/status) — só quem ainda tem acesso liberado
-- consegue revogar (ou reativar) alguém (pela aba Acesso restrito → Acessos). O cadastro da
-- própria linha acontece sozinho, pelo gatilho lá em cima, já liberado — ninguém insere aqui
-- direto.
drop policy if exists "Leitura autenticada" on usuarios_aprovados;
create policy "Leitura autenticada" on usuarios_aprovados for select using (auth.role() = 'authenticated');
drop policy if exists "Aprovação só por quem já é aprovado" on usuarios_aprovados;
create policy "Aprovação só por quem já é aprovado" on usuarios_aprovados for update
  using (public.esta_aprovado()) with check (true);

drop policy if exists "Leitura pública" on stakeholders;
create policy "Leitura pública" on stakeholders for select using (true);
drop policy if exists "Inserção pública" on stakeholders;
create policy "Inserção pública" on stakeholders for insert with check (true);
drop policy if exists "Atualização pública" on stakeholders;
create policy "Atualização pública" on stakeholders for update using (true) with check (true);
drop policy if exists "Remoção pública" on stakeholders;
create policy "Remoção pública" on stakeholders for delete using (true);

drop policy if exists "Leitura pública" on captacoes;
create policy "Leitura pública" on captacoes for select using (true);

drop policy if exists "Cadastro público" on captacoes;
create policy "Cadastro público" on captacoes for insert with check (true);
drop policy if exists "Edição pública" on captacoes;
create policy "Edição pública" on captacoes for update using (true) with check (true);
drop policy if exists "Remoção pública" on captacoes;
create policy "Remoção pública" on captacoes for delete using (true);

drop policy if exists "Leitura pública" on captacao_eventos;
create policy "Leitura pública" on captacao_eventos for select using (true);
drop policy if exists "Inserção pública" on captacao_eventos;
create policy "Inserção pública" on captacao_eventos for insert with check (true);
drop policy if exists "Atualização pública" on captacao_eventos;
create policy "Atualização pública" on captacao_eventos for update using (true) with check (true);
drop policy if exists "Remoção pública" on captacao_eventos;
create policy "Remoção pública" on captacao_eventos for delete using (true);

-- 6) ARMAZENAMENTO DE ANEXOS (fotos/documentos do formulário) -----------------
insert into storage.buckets (id, name, public)
values ('anexos', 'anexos', true)
on conflict (id) do nothing;

drop policy if exists "Leitura pública dos anexos" on storage.objects;
create policy "Leitura pública dos anexos" on storage.objects for select
  using (bucket_id = 'anexos');

drop policy if exists "Upload público de anexos" on storage.objects;
create policy "Upload público de anexos" on storage.objects for insert
  with check (bucket_id = 'anexos');

-- 7) TEMPO REAL ----------------------------------------------------------------
-- Faz quem estiver com o Dashboard/Cadastro aberto no navegador ver um cadastro novo (feito
-- por outra pessoa) aparecer sozinho, sem precisar recarregar a página.
do $$
begin
  alter publication supabase_realtime add table captacoes;
exception when duplicate_object then
  null; -- já estava habilitado — tudo bem, só ignora
end $$;

